namespace COMPEL.Services.Supervision;

/// <summary>
///     Writes "KONGOR/configuration/autoexec.cfg" in the installation directory, the configuration file that the manager and its match servers run at the end of their start-up, through the mod stack.
///     COMPEL rewrites it before every launch, so that the file always holds COMPEL's settings; the distribution's manifest keeps it out of synchronisation.
/// </summary>
public static class CustomConfiguration
{
    // The File Runs After The Manager's Own Settings And Those It Gives Each Match Server, So It Holds Only Settings That Every Process Shares, Never A Port, A Login, A Name, Or An Affinity
    private const string Content =
        """
        // autoexec.cfg auto-generated by COMPEL before every launch of the manager
        // the manager and every match server run it at the end of their start-up, after their own settings, so it holds only settings that every process shares

        // debugging
        set sys_dumpOnFatal true
        set con_verbose true

        """;

    /// <summary>
    ///     Writes the file beneath <paramref name="installationDirectory"/>, replacing any earlier copy, and returns its path.
    /// </summary>
    public static string Write(string installationDirectory)
    {
        string path = Path.Combine(installationDirectory, "KONGOR", "configuration", "autoexec.cfg");

        Directory.CreateDirectory(Path.GetDirectoryName(path) ?? throw new InvalidOperationException("The Custom Configuration File Has No Directory"));

        File.WriteAllText(path, Content);

        return path;
    }
}
